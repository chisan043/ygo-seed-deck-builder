  function key(value) {
    return String(value || "").normalize("NFKC").toLowerCase().replace(/[^\p{L}\p{N}]+/gu, "");
  }
  // Never let a later alias silently replace an earlier meaning.
  function compile(themeRecords, cardNames, otherMeanings = {}) {
    const targets = new Map();
    const deckAliases = {};
    const add = (alias, target) => {
      const normalized = key(alias);
      if (!normalized) return;
      if (!targets.has(normalized)) targets.set(normalized, new Map());
      targets.get(normalized).set(target.cardId ? `card:${target.cardId}` : `deck:${target.archetype}`, target);
    };
    for (const record of themeRecords) for (const alias of record.aliases) {
      deckAliases[alias] ||= record.archetype;
      add(alias, { archetype: record.archetype });
    }
    for (const [id, aliases] of Object.entries(cardNames)) for (const alias of aliases) add(alias, { cardId: Number(id) });
    for (const [alias, meanings] of Object.entries(otherMeanings)) for (const meaning of meanings) add(alias, meaning);
    return { deckAliases, ambiguousAliases: Object.fromEntries([...targets].filter(([, meanings]) => meanings.size > 1).map(([alias, meanings]) => [alias, [...meanings.values()]])) };
  }
  return { records, cardAliases, coreIds, confusables, key, compile, ...compile(records, cardAliases, confusables) };
